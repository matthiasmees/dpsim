function build_smallgrid_model(mode, fmuPath, modelPath, dt, stopTime, loadStepTime)
% Build a closed-loop Simulink ODE model of the complete small PI-line grid.
% No DPsim network code or replayed network data is used in this model.
if ~(strcmp(mode,'native')||strcmp(mode,'cs'))
    error('mode must be native or cs');
end
[~,mdl]=fileparts(modelPath);
if bdIsLoaded(mdl), close_system(mdl,0); end
if isfile(modelPath), delete(modelPath); end
new_system(mdl);
assignin('base','dt',dt); assignin('base','stopTime',stopTime);
assignin('base','loadStepTime',loadStepTime);
set_param(mdl,'Solver','ode14x','SolverType','Fixed-step', ...
    'NumberNewtonIterations','2','FixedStep','dt','StopTime','stopTime', ...
    'SaveTime','off','SaveOutput','off','ReturnWorkspaceOutputs','on', ...
    'SignalLogging','off');

% Initial electrical states are the FMU reset operating point. The source
% phasors below reproduce the line drop at that same initial instant.
line0 = [-222.333110114; 366.077037809; -143.743927695];
i0 = [-234.627119307; 325.134234647; -90.5071153404];
v0 = [288466.352188; -200716.863664; -87749.488524];
add_block('simulink/Sources/Clock',[mdl '/Simulation time'], ...
    'Position',[60 245 90 265]);
add_block('simulink/Sources/Constant',[mdl '/Load step time'], ...
    'Value','loadStepTime','Position',[60 300 120 330]);
add_block('simulink/Continuous/Integrator',[mdl '/PI line series current'], ...
    'InitialCondition',mat2str(line0,16),'Position',[190 155 230 195]);
add_block('simulink/Continuous/Integrator',[mdl '/PCC voltage'], ...
    'InitialCondition',mat2str(v0,16),'Position',[190 255 230 295]);

if strcmp(mode,'native')
    add_block('simulink/Continuous/Integrator',[mdl '/Inverter passive current state'], ...
        'InitialCondition',mat2str(i0,16),'Position',[190 355 230 395]);
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
        [mdl '/Closed-loop PI line and inverter equations'], ...
        'Position',[350 205 580 365]);
    chart=sfroot().find('-isa','Stateflow.EMChart','Path',[mdl '/Closed-loop PI line and inverter equations']);
    chart.Script=nativeEquations();
    add_line(mdl,'Simulation time/1','Closed-loop PI line and inverter equations/1');
    add_line(mdl,'Load step time/1','Closed-loop PI line and inverter equations/5');
    add_line(mdl,'PI line series current/1','Closed-loop PI line and inverter equations/2');
    add_line(mdl,'PCC voltage/1','Closed-loop PI line and inverter equations/3');
    add_line(mdl,'Inverter passive current state/1','Closed-loop PI line and inverter equations/4');
    add_line(mdl,'Closed-loop PI line and inverter equations/1','PI line series current/1');
    add_line(mdl,'Closed-loop PI line and inverter equations/2','PCC voltage/1');
    add_line(mdl,'Closed-loop PI line and inverter equations/3','Inverter passive current state/1');
    currentPath='Inverter passive current state/1';
else
    addpath(fileparts(fmuPath));
    add_block('simulink/Discrete/Zero-Order Hold',[mdl '/FMU voltage sample'], ...
        'SampleTime','dt','Position',[300 260 340 300]);
    add_block('simulink/Signal Routing/Demux',[mdl '/Split PCC voltage abc'], ...
        'Outputs','3','Position',[365 255 370 305]);
    add_block('simulink_extras/FMU Import/FMU',[mdl '/Averaged inverter FMI CS'], ...
        'FMUName','IEEE39AvgInverter.fmu','FMUMode','CoSimulation', ...
        'FMUInputMapping','Flat','FMUOutputMapping','Flat', ...
        'Position',[420 245 610 355]);
    add_block('simulink/Signal Routing/Mux',[mdl '/Join inverter passive current abc'], ...
        'Inputs','3','Position',[650 270 655 330]);
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
        [mdl '/Closed-loop PI line equations'], 'Position',[740 195 960 335]);
    chart=sfroot().find('-isa','Stateflow.EMChart','Path',[mdl '/Closed-loop PI line equations']);
    chart.Script=networkEquations(false);
    add_line(mdl,'Simulation time/1','Closed-loop PI line equations/1');
    add_line(mdl,'Load step time/1','Closed-loop PI line equations/5');
    add_line(mdl,'PI line series current/1','Closed-loop PI line equations/2');
    add_line(mdl,'PCC voltage/1','FMU voltage sample/1');
    add_line(mdl,'FMU voltage sample/1','Split PCC voltage abc/1');
    add_line(mdl,'PCC voltage/1','Closed-loop PI line equations/3');
    for phase=1:3
        add_line(mdl,sprintf('Split PCC voltage abc/%d',phase),sprintf('Averaged inverter FMI CS/%d',phase));
        add_line(mdl,sprintf('Averaged inverter FMI CS/%d',phase),sprintf('Join inverter passive current abc/%d',phase));
    end
    add_line(mdl,'Join inverter passive current abc/1','Closed-loop PI line equations/4');
    add_line(mdl,'Closed-loop PI line equations/1','PI line series current/1');
    add_line(mdl,'Closed-loop PI line equations/2','PCC voltage/1');
    currentPath='Join inverter passive current abc/1';
end

add_block('simulink/Sinks/To Workspace',[mdl '/Log PCC voltage'], ...
    'VariableName','pcc_voltage','SaveFormat','Timeseries','Position',[300 430 430 465]);
add_block('simulink/Sinks/To Workspace',[mdl '/Log inverter current'], ...
    'VariableName','inverter_current','SaveFormat','Timeseries','Position',[500 430 635 465]);
add_line(mdl,'PCC voltage/1','Log PCC voltage/1');
add_line(mdl,currentPath,'Log inverter current/1');
set_param(mdl,'SimulationCommand','update');
save_system(mdl,modelPath); close_system(mdl,0);
fprintf('Saved closed-loop Simulink %s model: %s\n',mode,modelPath);
end

function text = nativeEquations()
text = sprintf([ ...
 'function [diLine,dvPcc,diInv] = fcn(t,iLine,vPcc,iInv,loadStepTime)\n' ...
 '%%#codegen\n' ...
 'R=0.30; L=2.0e-2; C=5.0e-7; f=60; w=2*pi*f; tau=5e-3;\n' ...
 'Vpk=293875.37516493094; phi=[-0.22934586162574844;-2.3237409640189437;1.8650492407674475];\n' ...
 'vsrc=Vpk*cos(w*t+phi);\n' ...
 'P=125e6; Q=80.881e6; Vnom=345e3; Ipu=1.20;\n' ...
 'alpha=(2/3)*(vPcc(1)-0.5*vPcc(2)-0.5*vPcc(3)); beta=(2/3)*(sqrt(3)/2)*(vPcc(2)-vPcc(3)); v2=alpha*alpha+beta*beta;\n' ...
 'if v2<1, iRef=zeros(3,1); else\n' ...
 'k=2/(3*v2); ia=k*(P*alpha+Q*beta); ib=k*(P*beta-Q*alpha); imax=Ipu*sqrt(2)*hypot(P,Q)/(sqrt(3)*Vnom); imag=hypot(ia,ib);\n' ...
 'if imag>imax, ia=ia*imax/imag; ib=ib*imax/imag; end\n' ...
 'iRef=[-ia;0.5*ia-sqrt(3)/2*ib;0.5*ia+sqrt(3)/2*ib]; end\n' ...
 'iLoad=zeros(3,1); if t>=loadStepTime, iLoad=vPcc/(362215.5^2/(50e6)); end\n' ...
 'diLine=(vsrc-vPcc-R*iLine)/L; dvPcc=(iLine-iInv-iLoad)/C; diInv=(iRef-iInv)/tau;\n' ...
 'end\n']);
end

function text = networkEquations(~)
text = sprintf([ ...
 'function [diLine,dvPcc] = fcn(t,iLine,vPcc,iInv,loadStepTime)\n' ...
 '%%#codegen\n' ...
 'R=0.30; L=2.0e-2; C=5.0e-7; f=60; w=2*pi*f;\n' ...
 'Vpk=293875.37516493094; phi=[-0.22934586162574844;-2.3237409640189437;1.8650492407674475]; vsrc=Vpk*cos(w*t+phi);\n' ...
 'iLoad=zeros(3,1); if t>=loadStepTime, iLoad=vPcc/(362215.5^2/(50e6)); end\n' ...
 'diLine=(vsrc-vPcc-R*iLine)/L; dvPcc=(iLine-iInv-iLoad)/C;\n' ...
 'end\n']);
end
