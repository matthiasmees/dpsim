function build_ieee39_closed_loop(fmuPath, networkLibrary, modelPath, dt, stopTime, loadStepTime)
% Build the matched closed-loop IEEE39 model. The DPsim network S-function
% hosts the exact C++ case and the FMI Import block is the inverter element.
mdl = 'IEEE39_ClosedLoop';
if bdIsLoaded(mdl), close_system(mdl, 0); end
if isfile(modelPath), delete(modelPath); end
addpath(fileparts(fmuPath));
new_system(mdl);
set_param(mdl, 'Solver', 'FixedStepDiscrete', 'SolverType', 'Fixed-step', ...
    'FixedStep', 'dt', 'StopTime', 'stopTime', 'SaveTime', 'off', ...
    'SaveOutput', 'off', 'ReturnWorkspaceOutputs', 'on', ...
    'SignalLogging', 'off');
assignin('base', 'dt', dt);
assignin('base', 'stopTime', stopTime);
assignin('base', 'loadStepTime', loadStepTime);

add_block('simulink/User-Defined Functions/S-Function', [mdl '/IEEE39 DPsim network'], ...
    'FunctionName', 'ieee39_network_sfun', ...
    'Parameters', 'dt,stopTime,loadStepTime', 'Position', [95 180 270 310]);
add_block('simulink/Signal Routing/Selector', [mdl '/Bus 30 terminal voltage'], ...
    'InputPortWidth', '119', 'Indices', '88:90', 'Position', [325 205 410 245]);
add_block('simulink/Signal Routing/Demux', [mdl '/Split voltage abc'], ...
    'Outputs', '3', 'Position', [435 200 440 250]);
add_block('simulink_extras/FMU Import/FMU', [mdl '/IEEE39 averaged inverter FMI CS'], ...
    'FMUName', 'IEEE39AvgInverter.fmu', 'FMUMode', 'CoSimulation', ...
    'FMUInputMapping', 'Flat', 'FMUOutputMapping', 'Flat', ...
    'Position', [480 170 660 300]);
add_block('simulink/Sinks/To Workspace', [mdl '/Log all bus voltages'], ...
    'VariableName', 'bus_voltage', 'SaveFormat', 'Timeseries', ...
    'Position', [325 360 455 395]);
add_block('simulink/Sinks/To Workspace', [mdl '/Log inverter current'], ...
    'VariableName', 'inverter_current', 'SaveFormat', 'Timeseries', ...
    'Position', [720 210 850 245]);
add_block('simulink/Signal Routing/Mux', [mdl '/Join current abc'], ...
    'Inputs', '3', 'Position', [695 325 700 385]);
add_block('simulink/Signal Routing/Selector', [mdl '/Network timing'], ...
    'InputPortWidth', '119', 'Indices', '118:119', 'Position', [325 420 410 460]);
add_block('simulink/Sinks/To Workspace', [mdl '/Log network timing'], ...
    'VariableName', 'network_timing', 'SaveFormat', 'Timeseries', ...
    'Position', [465 420 595 455]);

add_line(mdl, 'IEEE39 DPsim network/1', 'Bus 30 terminal voltage/1');
add_line(mdl, 'Bus 30 terminal voltage/1', 'Split voltage abc/1');
for phase = 1:3
    add_line(mdl, sprintf('Split voltage abc/%d', phase), ...
        sprintf('IEEE39 averaged inverter FMI CS/%d', phase));
    add_line(mdl, sprintf('IEEE39 averaged inverter FMI CS/%d', phase), ...
        sprintf('Join current abc/%d', phase));
end
add_line(mdl, 'Join current abc/1', 'IEEE39 DPsim network/1');
add_line(mdl, 'IEEE39 DPsim network/1', 'Log all bus voltages/1');
add_line(mdl, 'Join current abc/1', 'Log inverter current/1');
add_line(mdl, 'IEEE39 DPsim network/1', 'Network timing/1');
add_line(mdl, 'Network timing/1', 'Log network timing/1');
set_param(mdl, 'SimulationCommand', 'update');
save_system(mdl, modelPath);
close_system(mdl, 0);
fprintf('Saved matched closed-loop IEEE39 model: %s\n', modelPath);
end
