function build_ieee39_closed_loop_native(modelPath, dt, stopTime, loadStepTime)
% Full IEEE39 network in closed loop with the averaged inverter implemented
% natively in Simulink. The network block is the same DPsim MNA S-function.
mdl = 'IEEE39_ClosedLoop_Native';
if bdIsLoaded(mdl), close_system(mdl, 0); end
if isfile(modelPath), delete(modelPath); end
assignin('base', 'dt', dt);
assignin('base', 'stopTime', stopTime);
assignin('base', 'loadStepTime', loadStepTime);
new_system(mdl);
% Use Simulink's fixed-step implicit solver with a fixed two-iteration
% Newton budget for the native inverter states.
set_param(mdl, 'Solver', 'ode14x', 'SolverType', 'Fixed-step', ...
    'NumberNewtonIterations', '2', ...
    'FixedStep', 'dt', 'StopTime', 'stopTime', 'SaveTime', 'off', ...
    'SaveOutput', 'off', 'ReturnWorkspaceOutputs', 'on', ...
    'SignalLogging', 'off');
add_block('simulink/User-Defined Functions/S-Function', [mdl '/IEEE39 DPsim network'], ...
    'FunctionName', 'ieee39_network_sfun', ...
    'Parameters', 'dt,stopTime,loadStepTime', 'Position', [95 210 270 340]);
add_block('simulink/Signal Routing/Selector', [mdl '/Bus 30 terminal voltage'], ...
    'InputPortWidth', '119', 'Indices', '88:90', 'Position', [315 220 400 260]);
add_block('simulink/Signal Routing/Demux', [mdl '/Split voltage abc'], ...
    'Outputs', '3', 'Position', [430 215 435 265]);
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [mdl '/Initialize current from network voltage'], ...
    'Position', [490 325 680 425]);
initChart = sfroot().find('-isa', 'Stateflow.EMChart', ...
    'Path', [mdl '/Initialize current from network voltage']);
initChart.Script = sprintf([ ...
    'function [ia0,ib0,ic0] = fcn(va,vb,vc)\n' ...
    '%%#codegen\n' ...
    'P=125e6; Q=80.881e6; Vnom=345e3; Ipu=1.20;\n' ...
    'a=(2/3)*(va-0.5*vb-0.5*vc);\n' ...
    'b=(2/3)*(sqrt(3)/2)*(vb-vc); v2=a*a+b*b;\n' ...
    'if v2<1, ia0=0; ib0=0; ic0=0; else\n' ...
    ' k=2/(3*v2); ialpha=k*(P*a+Q*b); ibeta=k*(P*b-Q*a);\n' ...
    ' imax=Ipu*sqrt(2)*hypot(P,Q)/(sqrt(3)*Vnom); imag=hypot(ialpha,ibeta);\n' ...
    ' if imag>imax, ialpha=ialpha*imax/imag; ibeta=ibeta*imax/imag; end\n' ...
    ' ia0=-ialpha; ib0=0.5*ialpha-sqrt(3)/2*ibeta;\n' ...
    ' ic0=0.5*ialpha+sqrt(3)/2*ibeta; end\n' ...
    'end\n']);
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [mdl '/Native averaged inverter'], 'Position', [490 180 680 300]);
chart = sfroot().find('-isa', 'Stateflow.EMChart', ...
    'Path', [mdl '/Native averaged inverter']);
chart.Script = sprintf([ ...
    'function [dia,dib,dic] = fcn(va,vb,vc,ia0,ib0,ic0)\n' ...
    '%%#codegen\n' ...
    'P=125e6; Q=80.881e6; Vnom=345e3; Ipu=1.20; tau=5e-3;\n' ...
    'a=(2/3)*(va-0.5*vb-0.5*vc);\n' ...
    'b=(2/3)*(sqrt(3)/2)*(vb-vc); v2=a*a+b*b;\n' ...
    'if v2<1, iaref=0; ibref=0; icref=0; else\n' ...
    ' k=2/(3*v2); ialpha=k*(P*a+Q*b); ibeta=k*(P*b-Q*a);\n' ...
    ' imax=Ipu*sqrt(2)*hypot(P,Q)/(sqrt(3)*Vnom); imag=hypot(ialpha,ibeta);\n' ...
    ' if imag>imax, ialpha=ialpha*imax/imag; ibeta=ibeta*imax/imag; end\n' ...
    ' iaref=ialpha; ibref=-0.5*ialpha+sqrt(3)/2*ibeta;\n' ...
    ' icref=-0.5*ialpha-sqrt(3)/2*ibeta; end\n' ...
    ' dia=(-iaref-ia0)/tau; dib=(-ibref-ib0)/tau; dic=(-icref-ic0)/tau;\n' ...
    'end\n']);

for phase = 1:3
    y = 105 + 55*phase;
    add_block('simulink/Continuous/Integrator', ...
        [mdl '/Native current state ' char('a'+phase-1)], ...
        'InitialConditionSource', 'external', ...
        'Position', [720 y 755 y+30]);
end
add_block('simulink/Signal Routing/Mux', [mdl '/Inverter current abc'], ...
    'Inputs', '3', 'Position', [820 245 825 305]);
add_block('simulink/Sinks/To Workspace', [mdl '/Log inverter current'], ...
    'VariableName', 'inverter_current', 'SaveFormat', 'Timeseries', ...
    'Position', [875 250 1005 285]);
add_block('simulink/Sinks/To Workspace', [mdl '/Log all bus voltages'], ...
    'VariableName', 'bus_voltage', 'SaveFormat', 'Timeseries', ...
    'Position', [315 390 445 425]);
add_block('simulink/Signal Routing/Selector', [mdl '/Network timing'], ...
    'InputPortWidth', '119', 'Indices', '118:119', 'Position', [315 445 400 485]);
add_block('simulink/Sinks/To Workspace', [mdl '/Log network timing'], ...
    'VariableName', 'network_timing', 'SaveFormat', 'Timeseries', ...
    'Position', [465 450 595 485]);

add_line(mdl, 'IEEE39 DPsim network/1', 'Bus 30 terminal voltage/1');
add_line(mdl, 'IEEE39 DPsim network/1', 'Log all bus voltages/1');
add_line(mdl, 'IEEE39 DPsim network/1', 'Network timing/1');
add_line(mdl, 'Network timing/1', 'Log network timing/1');
add_line(mdl, 'Bus 30 terminal voltage/1', 'Split voltage abc/1');
for phase = 1:3
    add_line(mdl, sprintf('Split voltage abc/%d', phase), ...
        sprintf('Native averaged inverter/%d', phase));
    state = sprintf('Native current state %c', char('a'+phase-1));
    add_line(mdl, [state '/1'], ...
        sprintf('Native averaged inverter/%d', phase+3));
    add_line(mdl, sprintf('Native averaged inverter/%d', phase), [state '/1']);
    add_line(mdl, [state '/1'], sprintf('Inverter current abc/%d', phase));
    add_line(mdl, sprintf('Split voltage abc/%d', phase), ...
        sprintf('Initialize current from network voltage/%d', phase));
    add_line(mdl, sprintf('Initialize current from network voltage/%d', phase), ...
        [state '/2']);
end
add_line(mdl, 'Inverter current abc/1', 'IEEE39 DPsim network/1');
add_line(mdl, 'Inverter current abc/1', 'Log inverter current/1');
set_param(mdl, 'SimulationCommand', 'update');
save_system(mdl, modelPath);
close_system(mdl, 0);
fprintf('Saved native closed-loop IEEE39 model: %s\n', modelPath);
end

function current = localNativeCurrent(vabc)
P = 125e6; Q = 80.881e6; Vnom = 345e3; Ipu = 1.20;
alpha = (2/3)*(vabc(1)-0.5*vabc(2)-0.5*vabc(3));
beta = (2/3)*(sqrt(3)/2)*(vabc(2)-vabc(3));
v2 = alpha*alpha + beta*beta;
if v2 < 1, current = [0;0;0]; return; end
k = 2/(3*v2); ia = k*(P*alpha+Q*beta); ib = k*(P*beta-Q*alpha);
imax = Ipu*sqrt(2)*hypot(P,Q)/(sqrt(3)*Vnom); imag = hypot(ia,ib);
if imag > imax, ia=ia*imax/imag; ib=ib*imax/imag; end
current = [-ia; 0.5*ia-sqrt(3)/2*ib; 0.5*ia+sqrt(3)/2*ib];
end
