function run_native_replay(inputCsv, outputCsv)
% Run the average inverter equations natively in Simulink against a recorded
% IEEE39 PCC voltage trace. This is an open-loop boundary replay reference;
% the voltage record is identical to the DPsim case named in inputCsv.
arguments
    inputCsv (1,:) char
    outputCsv (1,:) char
end

here = fileparts(mfilename('fullpath'));
caseDir = fileparts(here);
modelFile = fullfile(here, 'IEEE39_AvgInverter_Native_MatchedInit.slx');
T = readtable(inputCsv, 'VariableNamingRule', 'preserve');
time = T.time;
vabc = [T.('inverter.v_0'), T.('inverter.v_1'), T.('inverter.v_2')];
if numel(time) < 2 || any(diff(time) <= 0)
    error('Input voltage trace needs at least two increasing time samples.');
end
initialCurrent = localPassiveCurrent(vabc(1,:));

mdl = 'IEEE39_AvgInverter_Native_MatchedInit';
if bdIsLoaded(mdl)
    close_system(mdl, 0);
end
if isfile(modelFile)
    load_system(modelFile);
else
    new_system(mdl);
    add_block('simulink/Ports & Subsystems/In1', [mdl '/v_abc'], ...
        'PortDimensions', '3', 'Position', [35 100 65 120]);
    add_block('simulink/Signal Routing/Demux', [mdl '/SplitVoltage'], ...
        'Outputs', '3', 'Position', [100 75 105 145]);
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
        [mdl '/Average_PQ_Current_Controller'], 'Position', [160 65 330 150]);
    for phase = 1:3
        add_block('simulink/Continuous/Integrator', ...
            [mdl '/Current_State_' num2str(phase)], ...
            'InitialCondition', num2str(initialCurrent(phase), '%.17g'), ...
            'Position', [385 55+50*phase 420 85+50*phase]);
    end
    add_block('simulink/Signal Routing/Mux', [mdl '/JoinCurrent'], ...
        'Inputs', '3', 'Position', [460 75 465 145]);
    add_block('simulink/Ports & Subsystems/Out1', [mdl '/i_abc'], ...
        'PortDimensions', '3', 'Position', [500 100 530 120]);
    stateflowRoot = sfroot();
    chart = stateflowRoot.find('-isa', 'Stateflow.EMChart', ...
        'Path', [mdl '/Average_PQ_Current_Controller']);
    chart.Script = sprintf([ ...
        'function [dia,dib,dic] = fcn(va,vb,vc,ia0,ib0,ic0)\n' ...
        '%%#codegen\n' ...
        'P = 125e6; Q = 80.881e6; Vnom = 345e3; Ipu = 1.20; tau = 5e-3;\n' ...
        'a = (2/3)*(va-0.5*vb-0.5*vc);\n' ...
        'b = (2/3)*(sqrt(3)/2)*(vb-vc);\n' ...
        'v2 = a*a + b*b;\n' ...
        'if v2 < 1, iaref = 0; ibref = 0; icref = 0;\n' ...
        'else\n' ...
        '  k = 2/(3*v2);\n' ...
        '  ialpha = k*(P*a + Q*b); ibeta = k*(P*b-Q*a);\n' ...
        '  imax = Ipu*sqrt(2)*hypot(P,Q)/(sqrt(3)*Vnom);\n' ...
        '  imag = hypot(ialpha,ibeta);\n' ...
        '  if imag > imax, ialpha=ialpha*imax/imag; ibeta=ibeta*imax/imag; end\n' ...
        '  iaref = ialpha; ibref = -0.5*ialpha+sqrt(3)/2*ibeta;\n' ...
        '  icref = -0.5*ialpha-sqrt(3)/2*ibeta;\n' ...
        'end\n' ...
        'dia=(-iaref-ia0)/tau; dib=(-ibref-ib0)/tau; dic=(-icref-ic0)/tau;\n' ...
        'end\n']);
    set_param(mdl, 'SimulationCommand', 'update');
    add_line(mdl, 'v_abc/1', 'SplitVoltage/1');
    for phase = 1:3
        add_line(mdl, ['SplitVoltage/' num2str(phase)], ...
            ['Average_PQ_Current_Controller/' num2str(phase)]);
        add_line(mdl, ['Current_State_' num2str(phase) '/1'], ...
            ['Average_PQ_Current_Controller/' num2str(phase+3)]);
        add_line(mdl, ['Average_PQ_Current_Controller/' num2str(phase)], ...
            ['Current_State_' num2str(phase) '/1']);
        add_line(mdl, ['Current_State_' num2str(phase) '/1'], ...
            ['JoinCurrent/' num2str(phase)]);
    end
    add_line(mdl, 'JoinCurrent/1', 'i_abc/1');
    set_param(mdl, 'Solver', 'ode4', 'FixedStep', '1e-6', ...
        'StopTime', num2str(time(end), '%.17g'), 'SaveOutput', 'on', ...
        'OutputSaveName', 'yout', 'SaveFormat', 'Dataset', ...
        'LoadExternalInput', 'on', 'ExternalInput', 'vabc');
    save_system(mdl, modelFile);
end

set_param(mdl, 'Solver', 'ode4', 'FixedStep', '1e-6', ...
    'StopTime', num2str(time(end), '%.17g'), 'SaveOutput', 'on', ...
    'OutputSaveName', 'yout', 'SaveFormat', 'Dataset', ...
    'LoadExternalInput', 'on', 'ExternalInput', 'vabc');
input = timeseries(vabc, time);
simInput = Simulink.SimulationInput(mdl);
simInput = simInput.setVariable('vabc', input);
simInput = simInput.setModelParameter('StopTime', num2str(time(end), '%.17g'));
tic;
simOutput = sim(simInput);
runtimeS = toc;
currentSeries = simOutput.yout.getElement(1).Values;
tNative = currentSeries.Time;
iNative = squeeze(currentSeries.Data);
if size(iNative, 2) ~= 3 && size(iNative, 1) == 3
    iNative = iNative.';
end
out = table(tNative, iNative(:,1), iNative(:,2), iNative(:,3), ...
    'VariableNames', {'time','i_a','i_b','i_c'});
writetable(out, outputCsv);
manifest = struct('mode','native_simulink_replay', ...
    'runtime_s',runtimeS,'solver','ode4','fixed_step_s',1e-6, ...
    'stop_time_s',time(end),'input_csv',inputCsv, ...
    'output_csv',outputCsv,'reference_type','open_loop_voltage_replay');
[folder,~,~] = fileparts(outputCsv);
if isempty(folder), folder = pwd; end
fid = fopen(fullfile(folder,'native_timing.json'),'w');
cleanup = onCleanup(@() fclose(fid));
fwrite(fid, jsonencode(manifest, 'PrettyPrint', true));
fwrite(fid, newline);
fprintf('Native Simulink replay runtime_s=%.6f, samples=%d\n', ...
    runtimeS, height(out));
end

function current = localPassiveCurrent(vabc)
P = 125e6; Q = 80.881e6; Vnom = 345e3; Ipu = 1.20;
alpha = (2/3)*(vabc(1)-0.5*vabc(2)-0.5*vabc(3));
beta = (2/3)*(sqrt(3)/2)*(vabc(2)-vabc(3));
v2 = alpha*alpha + beta*beta;
if v2 < 1
    current = [0;0;0];
    return;
end
k = 2/(3*v2);
ialpha = k*(P*alpha + Q*beta);
ibeta = k*(P*beta-Q*alpha);
imax = Ipu*sqrt(2)*hypot(P,Q)/(sqrt(3)*Vnom);
imag = hypot(ialpha,ibeta);
if imag > imax
    ialpha = ialpha*imax/imag;
    ibeta = ibeta*imax/imag;
end
injection = [ialpha; -0.5*ialpha+sqrt(3)/2*ibeta; ...
    -0.5*ialpha-sqrt(3)/2*ibeta];
current = -injection;
end
